from pydantic import BaseModel, Field
from langchain.tools import tool

BUSES = {
    "B101": {"from": "Hyderabad", "to": "Bangalore", "date": "2026-12-05",
             "time": "9:00 PM", "distance": 570, "fare": 900, "seats": 12},
    "B102": {"from": "Hyderabad", "to": "Bangalore", "date": "2026-12-05",
             "time": "10:00 PM", "distance": 570, "fare": 750, "seats": 5},
    "B103": {"from": "Vijayawada", "to": "Chennai", "date": "2026-12-05",
             "time": "8:00 PM", "distance": 450, "fare": 650, "seats": 8}
}

class Booking(BaseModel):
    name: str = Field(description="Passenger name")
    bus_id: str = Field(description="Selected bus ID")
    date: str = Field(description="Journey date in YYYY-MM-DD")
    seats: int = Field(ge=1, description="Number of seats")

@tool
def search_buses(from_city: str, to_city: str, date: str) -> str:
    """Search buses and show time, distance, fare and available seats."""
    found = [f"{i}: {b['from']} to {b['to']}, {b['time']}, {b['distance']} km, "
             f"Rs {b['fare']} per seat, {b['seats']} seats available"
             for i, b in BUSES.items()
             if b["from"].lower() == from_city.lower()
             and b["to"].lower() == to_city.lower() and b["date"] == date]
    return "\n".join(found) if found else "No buses found for this route and date."

@tool
def book_bus(name: str, bus_id: str, date: str, seats: int) -> str:
    """Save a booking after the passenger confirms all booking details."""
    try:
        order = Booking(name=name, bus_id=bus_id, date=date, seats=seats)
        bus = BUSES[order.bus_id]
        if bus["date"] != date:
            return "That bus is not scheduled for this date."
        if bus["seats"] < seats:
            return f"Only {bus['seats']} seats are available."
        total = bus["fare"] * seats
        ws.append_row([order.name, order.bus_id, bus["from"], bus["to"],
                       order.date, order.seats, total])
        bus["seats"] -= seats
        return f"Booking saved to Google Sheets! {seats} seat(s), total Rs {total}."
    except Exception as e:
        return f"Booking failed: {e}"

from langchain.agents import create_agent

SYSTEM = """ROLE: You are TravelMate, a friendly bus booking assistant.
RULES: Use search_buses for route, date, fare, distance, timing and seat availability.
       Never invent bus details. Ask for missing information.
       Before booking, collect passenger name, bus ID, date and number of seats.
       Ask the passenger to confirm before calling book_bus.
       Call book_bus only after clear confirmation.
       After booking, confirm the total fare and say it was saved to Google Sheets.
FORMAT: Keep replies short and friendly. Reply in English or Telugu as the customer prefers."""

agent = create_agent(model=llm, tools=[search_buses, book_bus], system_prompt=SYSTEM)
history = []

def chat(text):
    global history
    try:
        result = agent.invoke({"messages": history + [{"role": "user", "content": text}]})
        history = result["messages"]
        return history[-1].content
    except Exception as e:
        return f"Agent error: {e}"

