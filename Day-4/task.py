from pydantic import BaseModel, Field
from typing import Literal
from langchain.tools import tool

BUSES = {
    "B101": {"from": "Hyderabad", "to": "Bangalore", "date": "2026-12-05", "time": "9:00 PM", "distance": 570, "fare": 900, "seats": 12},
    "B102": {"from": "Hyderabad", "to": "Bangalore", "date": "2026-12-05", "time": "10:00 PM", "distance": 570, "fare": 750, "seats": 5},
    "B103": {"from": "Vijayawada", "to": "Chennai", "date": "2026-12-05", "time": "8:00 PM", "distance": 450, "fare": 650, "seats": 8}
}

class Booking(BaseModel):
    name: str = Field(description="Passenger full name")
    bus_id: Literal["B101", "B102", "B103"] = Field(description="Selected bus ID")
    date: str = Field(description="Journey date in YYYY-MM-DD format")
    seats: int = Field(ge=1, description="Number of seats")

print("Booking model ready")

@tool
def search_buses(from_city: str, to_city: str, date: str) -> str:
    """Search buses by departure city, destination and date. Show time, distance, fare and available seats."""
    found = [
        f"{bus_id}: {bus['from']} to {bus['to']}, {bus['time']}, {bus['distance']} km, Rs {bus['fare']} per seat, {bus['seats']} seats available"
        for bus_id, bus in BUSES.items()
        if bus["from"].lower() == from_city.lower()
        and bus["to"].lower() == to_city.lower()
        and bus["date"] == date and bus["seats"] > 0
    ]
    return "\\n".join(found) if found else "No buses found for this route and date."

@tool
def log_booking(name: str, bus_id: str, date: str, seats: int) -> str:
    """Save a passenger's confirmed bus booking to the TravelMate Google Sheet."""
    if bus_id not in BUSES:
        return "Invalid bus ID."
    bus = BUSES[bus_id]
    if bus["date"] != date:
        return "This bus is not scheduled for that date."
    if seats < 1:
        return "Seat quantity must be at least 1."
    if bus["seats"] < seats:
        return f"Only {bus['seats']} seats are available."
    total = bus["fare"] * seats
    try:
        ws.append_row([name, bus_id, bus["from"], bus["to"], date, seats, total])
        bus["seats"] -= seats
        return f"Booking saved! {name}, {bus_id}, {seats} seat(s), total Rs {total}."
    except Exception as e:
        return f"Could not save booking: {e}"

