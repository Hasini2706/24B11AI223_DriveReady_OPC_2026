class Booking(BaseModel):
    name: str = Field(description="Passenger full name")
    bus_id: Literal["B101", "B102", "B103"] = Field(description="Selected bus ID")
    date: str = Field(description="Journey date in YYYY-MM-DD format")
    seats: int = Field(ge=1, description="Number of seats")

print("Sample buses and Booking model ready.")

@tool
def search_buses(from_city: str, to_city: str, date: str) -> str:
    """Search demo buses by departure city, destination city and journey date.
    Return matching bus IDs, departure times, distances, fares per seat and
    available seats. Do not invent a bus when no match exists."""
    matches = []
    for bus_id, bus in BUSES.items():
        if (bus["from"].lower() == from_city.lower()
            and bus["to"].lower() == to_city.lower()
            and bus["date"] == date and bus["seats"] > 0):
            matches.append(
                f"{bus_id}: {bus['from']} to {bus['to']}, {date}, {bus['time']}, "
                f"{bus['distance']} km, Rs {bus['fare']} per seat, "
                f"{bus['seats']} seats available"
            )
    return "\n".join(matches) if matches else "No matching demo buses found."

@tool
def log_booking(name: str, bus_id: str, date: str, seats: int) -> str:
    """Save a passenger's confirmed demo booking to the TravelMate Google Sheet.
    Validate the bus, date and seat count, calculate the total fare, and reduce
    available seats only after the spreadsheet row is saved successfully."""
    if bus_id not in BUSES:
        return "Booking failed: invalid bus ID."
    bus = BUSES[bus_id]
    if bus["date"] != date:
        return "Booking failed: this bus is not scheduled for that date."
    if seats < 1:
        return "Booking failed: seat quantity must be at least one."
    if bus["seats"] < seats:
        return f"Booking failed: only {bus['seats']} seats are available."

    total = bus["fare"] * seats
    try:
        ws.append_row([name, bus_id, bus["from"], bus["to"], date, seats, total])
        bus["seats"] -= seats
        return f"BOOKING SAVED: {name}, {bus_id}, {seats} seat(s), total Rs {total}."
    except Exception as e:
        return f"Booking failed: Google Sheets error: {e}"

