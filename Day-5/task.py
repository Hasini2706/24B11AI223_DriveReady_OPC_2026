@tool
def search_travelmate_faq(question: str) -> str:
    """Search TravelMate business knowledge about bus search requirements,
    passenger booking details, confirmation rules, demo bus IDs B101/B102/B103,
    routes, journey dates, departure times, distances, fares, seat availability,
    total fare calculation and Google Sheets booking records. Use for business
    and policy questions. If the facts do not answer the question, do not guess."""
    results = retriever.invoke(question)
    if not results:
        return "NO_KNOWLEDGE_FOUND: no matching TravelMate facts."
    return "\n".join(
        f"[Fact {doc.metadata['fact_number']}] {doc.page_content}"
        for doc in results
    )

